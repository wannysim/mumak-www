// Additive observation SQL. Existing 001–004/public financial v1 are unchanged.
import fs from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const contract = JSON.parse(await fs.readFile(new URL('src/lib/observation-contract.json', root), 'utf8'));
const sql = `-- Generated by scripts/generate-observation-migration.mjs; no production execution.
CREATE FUNCTION public.paper_observation_contract() RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path='' AS $schema$
 SELECT '${JSON.stringify(contract).replaceAll("'", "''")}'::jsonb
$schema$;
REVOKE ALL ON FUNCTION public.paper_observation_contract() FROM PUBLIC,anon,authenticated;

CREATE FUNCTION public.paper_observation_validate(p jsonb) RETURNS void LANGUAGE plpgsql IMMUTABLE SET search_path='' AS $$
DECLARE c jsonb:=public.paper_observation_contract(); ev jsonb; e jsonb; v jsonb; a jsonb; f text; k text; stamp timestamptz; latest timestamptz;
BEGIN
 IF octet_length(p::text)>2097152 THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
 SELECT jsonb_object_agg(x->>'id',x) INTO ev FROM jsonb_array_elements(p->'evidence') x;
 PERFORM public.paper_operations_check(p,c->'payload',c,ev);
 IF (SELECT count(*) FROM jsonb_object_keys(ev))<>jsonb_array_length(p->'evidence') OR left(p->>'session',7)<>p->>'month' THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
 FOR e IN SELECT * FROM jsonb_array_elements(p->'evidence') LOOP
  IF (e->>'evidenceAt')::timestamptz>(e->>'observedAt')::timestamptz OR (e->>'observedAt')::timestamptz>(p->>'exportedAt')::timestamptz THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  latest:=greatest(latest,(e->>'evidenceAt')::timestamptz);
 END LOOP;
 IF latest<>(p->>'sourceAsOf')::timestamptz OR latest>(p->>'exportedAt')::timestamptz OR (p->>'effectiveFrom')::timestamptz >= (p->>'effectiveThrough')::timestamptz THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
 FOR f,k IN SELECT * FROM (VALUES ('ingest','ingest-readback'),('schedule','schedule-receipt'),('collection','collector-receipt'),('publication','publication-receipt'),('decision','decision-record'),('account','risk-record'),('symbols','risk-record')) kinds(f,k) LOOP
  v:=p->f->'value';
  IF v='null'::jsonb THEN CONTINUE; END IF;
  IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements_text(p->f->'evidenceIds') ref WHERE ev->ref->>'kind'=k) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  stamp:=NULL;
  IF f IN ('collection','publication','account') THEN stamp:=(v->>'assessedAt')::timestamptz;
  ELSIF f='ingest' THEN stamp:=(v->>'readbackAt')::timestamptz;
  ELSIF f='decision' THEN stamp:=(v->>'at')::timestamptz; END IF;
  IF stamp IS NOT NULL AND NOT EXISTS(SELECT 1 FROM jsonb_array_elements_text(p->f->'evidenceIds') ref WHERE ev->ref->>'kind'=k AND (ev->ref->>'evidenceAt')::timestamptz=stamp) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF f IN ('collection','publication','account','decision') AND (stamp AT TIME ZONE 'America/New_York')::date<>(p->>'session')::date THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF f IN ('collection','publication','account') AND NOT ((p->>'effectiveFrom')::timestamptz<=stamp AND stamp<(v->>'validUntil')::timestamptz AND (v->>'validUntil')::timestamptz<=(p->>'effectiveThrough')::timestamptz) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF f='ingest' AND (v->>'snapshotAsOf')::timestamptz>stamp THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF f='schedule' AND ((v->>'opensAt')::timestamptz>=(v->>'closesAt')::timestamptz OR (v->>'nextExpectedAt')::timestamptz>(v->>'expectedBy')::timestamptz OR ((v->>'opensAt')::timestamptz AT TIME ZONE 'America/New_York')::date<>(p->>'session')::date OR ((v->>'closesAt')::timestamptz AT TIME ZONE 'America/New_York')::date<>(p->>'session')::date) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF f='symbols' THEN
   IF (SELECT count(DISTINCT s->>'symbol') FROM jsonb_array_elements(v) s)<>jsonb_array_length(v) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
   FOR e IN SELECT * FROM jsonb_array_elements(v) LOOP
    stamp:=(e->>'assessedAt')::timestamptz;
    IF NOT ((p->>'effectiveFrom')::timestamptz<=stamp AND stamp<(e->>'validUntil')::timestamptz AND (e->>'validUntil')::timestamptz<=(p->>'effectiveThrough')::timestamptz) OR (stamp AT TIME ZONE 'America/New_York')::date<>(p->>'session')::date THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
    IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements_text(e->'evidenceIds') ref WHERE ev->ref->>'kind'='risk-record' AND (ev->ref->>'evidenceAt')::timestamptz=stamp) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
    IF e->>'inputConfidence'='unknown' AND e->>'state' NOT IN ('unknown','hold') THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
    FOREACH k IN ARRAY ARRAY['entryPrice','sigmaEntry','highWater','mark','stopThreshold'] LOOP
     IF (e->>'inputConfidence'='validated' AND e->>k IS NULL) OR (e->>k)::numeric<=0 THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
    END LOOP;
    IF (e->>'exposureProxy')::numeric<0 OR (e->>'gamma')::numeric<=0 THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
    IF (e->>'targetQuantity')::numeric>(e->>'quantity')::numeric OR (e->>'state'='full-exit' AND (e->>'targetQuantity' IS DISTINCT FROM '0' OR e->>'reason' NOT IN ('symbol-stop','symbol-trim','account-stop'))) OR (e->>'state'='trim' AND (e->>'targetQuantity' IS NULL OR (e->>'targetQuantity')::numeric>=(e->>'quantity')::numeric OR e->>'reason'<>'symbol-trim')) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
   END LOOP;
  END IF;
 END LOOP;
 a:=p#>'{account,value}';
 IF a<>'null'::jsonb THEN
  IF (a->>'dailyStop')::numeric<>0.01 OR (a->>'monthlyStop')::numeric<>0.30 THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF a->>'state'='clear' AND (a->>'reason'<>'none' OR a->>'dailyReturn' IS NULL OR a->>'monthlyReturn' IS NULL OR (a->>'dailyReturn')::numeric<=-(a->>'dailyStop')::numeric OR (a->>'monthlyReturn')::numeric<=-(a->>'monthlyStop')::numeric) THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
  IF (a->>'state'='stopped' AND a->>'reason' NOT IN ('daily-loss-stop','monthly-loss-stop','both-loss-stops')) OR (a->>'state'='unknown' AND a->>'reason'<>'unknown') THEN RAISE EXCEPTION 'Invalid public observation'; END IF;
 END IF;
END $$;
REVOKE ALL ON FUNCTION public.paper_observation_validate(jsonb) FROM PUBLIC,anon,authenticated;

CREATE TABLE public.paper_observations (
 episode_id text NOT NULL, month text NOT NULL, session date NOT NULL, revision bigint NOT NULL CHECK(revision>0),
 source_as_of timestamptz NOT NULL, stored_at timestamptz NOT NULL DEFAULT clock_timestamp(), payload jsonb NOT NULL,
 PRIMARY KEY(episode_id,month,session), CHECK(to_char(session,'YYYY-MM')=month)
);
ALTER TABLE public.paper_observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paper_observations FORCE ROW LEVEL SECURITY;
REVOKE ALL ON public.paper_observations FROM PUBLIC,anon,authenticated,service_role;
GRANT SELECT ON public.paper_observations TO anon,authenticated,service_role;
CREATE POLICY paper_observations_read ON public.paper_observations FOR SELECT TO anon,authenticated,service_role USING(true);
CREATE FUNCTION public.publish_paper_observation(snapshot jsonb,expected_revision bigint) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE old public.paper_observations; n bigint; e jsonb;
BEGIN
 PERFORM public.paper_observation_validate(snapshot);
 IF expected_revision IS NULL OR expected_revision<0 OR expected_revision>=9007199254740991 THEN RAISE EXCEPTION 'Invalid revision'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('observation:'||(snapshot->>'episodeId')||':'||(snapshot->>'month')||':'||(snapshot->>'session'),0));
 SELECT * INTO old FROM public.paper_observations WHERE episode_id=snapshot->>'episodeId' AND month=snapshot->>'month' AND session=(snapshot->>'session')::date;
 IF coalesce(old.revision,0)<>expected_revision THEN RAISE EXCEPTION 'Revision conflict'; END IF;
 IF old.revision IS NOT NULL THEN
  IF public.paper_operations_meaningful(old.payload)=public.paper_operations_meaningful(snapshot) THEN RETURN old.revision; END IF;
  IF (snapshot->>'sourceAsOf')::timestamptz<=old.source_as_of OR snapshot->>'origin' IS DISTINCT FROM old.payload->>'origin' THEN RAISE EXCEPTION 'Stale or conflicting source'; END IF;
  FOR e IN SELECT * FROM jsonb_array_elements(old.payload->'evidence') LOOP
   IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(snapshot->'evidence') x WHERE x->>'id'=e->>'id' AND x->>'kind'=e->>'kind' AND (x->>'evidenceAt')::timestamptz>=(e->>'evidenceAt')::timestamptz) THEN RAISE EXCEPTION 'Evidence regressed'; END IF;
  END LOOP;
 END IF;
 n:=coalesce(old.revision,0)+1;
 INSERT INTO public.paper_observations(episode_id,month,session,revision,source_as_of,payload) VALUES(snapshot->>'episodeId',snapshot->>'month',(snapshot->>'session')::date,n,(snapshot->>'sourceAsOf')::timestamptz,snapshot)
 ON CONFLICT(episode_id,month,session) DO UPDATE SET revision=excluded.revision,source_as_of=excluded.source_as_of,payload=excluded.payload,stored_at=clock_timestamp();
 RETURN n;
END $$;
REVOKE ALL ON FUNCTION public.publish_paper_observation(jsonb,bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.publish_paper_observation(jsonb,bigint) TO service_role;
`;
const output = new URL('supabase/migrations/005_paper_observations.sql', root);
if (process.argv.includes('--check')) {
  if ((await fs.readFile(output, 'utf8')) !== sql) throw new Error('Observation migration is out of date');
} else await fs.writeFile(output, sql);
